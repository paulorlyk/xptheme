#!/bin/bash
# Build the XP-Classic theme files into build/XP-Classic-for-Mint, over a base application theme.
#
# usage: build.sh --scheme PATH [--base NAME|DIR] [--no-borders]
#                 (or set $XP_SCHEME, $XP_BASE, XP_NO_BORDERS=1)
#   PATH is Windows XP's "Windows Classic.theme" (C:\WINDOWS\Resources\Themes). Every colour,
#   size and font comes from its [Control Panel\Colors] and [Metrics]. The file is only read
#   from PATH.
#   --base: the theme XP-Classic inherits the rest of GTK's styling from, by name or folder
#   (../shared/tools/base.sh). Default Adwaita, GTK's own.
#   --no-borders: windows get the caption only, no frame (as maximized ones), so Electron apps
#   hidden to the tray don't come back shifted (a Muffin bug, see tools/gen_decorations.py).
#   Only needed with a Muffin older than upstream commit e2cb1fa6 (linuxmint/muffin#902).
set -euo pipefail
cd "$(dirname "$0")"

SCHEME="${XP_SCHEME:-}"
BASE="${XP_BASE:-Adwaita}"
NO_BORDERS="${XP_NO_BORDERS:-}"
while [ $# -gt 0 ]; do
  case "$1" in
    --scheme) SCHEME="$2"; shift 2 ;;
    --base) BASE="$2"; shift 2 ;;
    --no-borders) NO_BORDERS=1; shift ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -n "$SCHEME" ] || { echo "usage: build.sh --scheme '/path/to/Windows Classic.theme'" >&2; exit 2; }
[ -f "$SCHEME" ] || { echo "no such file: $SCHEME" >&2; exit 2; }
SC=(--scheme "$(realpath "$SCHEME")")

BUILD=build
THEME=XP-Classic-for-Mint   # must contain "mint": Nemo then skips its slow theme check (see ../CLAUDE.md)
OUT="$BUILD/$THEME"

if [ ! -x "$BUILD/venv/bin/python" ]; then
  python3 -m venv "$BUILD/venv"
  "$BUILD/venv/bin/pip" install -q pillow
fi
PY="$BUILD/venv/bin/python -I"

rm -rf "$OUT"
mkdir -p "$OUT/gtk-3.0/assets"
$PY tools/gen_decorations.py "$OUT/gtk-3.0/assets" "$OUT/gtk-3.0/classic-decorations.css" "${SC[@]}" \
  ${NO_BORDERS:+--no-borders}
if [ -n "$NO_BORDERS" ]; then echo none; else echo xp; fi > "$BUILD/borders"
# the Themes chooser preview
$PY tools/gen_thumbnail.py "$OUT/gtk-3.0/thumbnail.png" "${SC[@]}"
# Application widgets: one generator per classic-*.css, in cascade order (later files win at
# equal specificity). classic.css imports them in this order.
WIDGETS=(labels buttons checks scrollbars tabs fields toolbars lists frames sliders progress switches bars menus tooltips nemo)
for w in "${WIDGETS[@]}"; do
  $PY "tools/gen_$w.py" "$OUT/gtk-3.0/assets" "$OUT/gtk-3.0/classic-$w.css" "${SC[@]}"
done
{
  echo "/* XP Classic application widgets, in cascade order. Generated by build.sh. */"
  for w in "${WIDGETS[@]}"; do echo "@import url(\"classic-$w.css\");"; done
} > "$OUT/gtk-3.0/classic.css"
# the tests use the same file as their reference
realpath "$SCHEME" > "$BUILD/scheme.path"

. ../shared/tools/base.sh
resolve_base "$BASE" || true
write_gtk_css "$OUT/gtk-3.0" "XP Classic" classic-decorations.css classic.css
echo "$BASE_NAME" > "$BUILD/base.name"

cat > "$OUT/index.theme" <<EOF
[Desktop Entry]
Type=X-GNOME-Metatheme
Name=$THEME
Comment=Windows XP Classic controls (drawn from your Windows Classic.theme colour scheme)
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=$THEME
ButtonLayout=:minimize,maximize,close
EOF

cat > "$OUT/NOTICE" <<EOF
XP-Classic, built from the colour scheme in your own copy of Windows XP's
Windows Classic.theme.

The theme is generated code: its colours and sizes are read from that file, and
its glyphs are drawn by the build tool. It contains no Microsoft bitmaps or fonts.

Not affiliated with or endorsed by Microsoft. Microsoft, Windows and Windows XP
are trademarks of Microsoft Corporation.
EOF

echo "built $OUT"
