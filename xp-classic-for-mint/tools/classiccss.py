"""XP-Classic's helpers for the widget generators: the command line and the specificity boost.
The source-independent ones are shared/tools/gtkcss.py's, re-exported here.

Each generator writes one classic-*.css; build.sh's classic.css imports them in cascade order.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))   # python -I omits the script dir
sys.path.insert(1, str(Path(__file__).resolve().parents[2] / "shared/tools"))   # gtkcss, gtknodes
import scheme  # noqa: E402
from gtkcss import boost, rule, save, scaled, sels, sides, stripes, write  # noqa: E402,F401  (re-exported)

# Always-true :not(.classic-N) filters that out-rank base themes' long selectors (gtkcss.boost).
BOOST = boost("classic")


def run(title, *generators, post=None):
    """A generator's command line: <assets-dir> <out-css> --scheme PATH.

    Writes a header comment, then the rules every `generator(sch, assets)` returns, each passed
    through `post(rule)` if given."""
    args, sch = scheme.from_argv(sys.argv[1:])
    assets, out_css = (Path(p) for p in args[:2])
    out = []
    for g in generators:
        out += g(sch, assets)
    if post:
        out = [post(r) for r in out]
    header = f"/* {title} Generated by tools/{Path(sys.argv[0]).name} from the colour scheme. */\n"
    write(out_css, header, out)
