"""Helpers shared by the widget generators (gen_widgets, gen_checks, gen_scrollbars, gen_tabs,
gen_fields, gen_toolbars, gen_headers, gen_sliders, gen_progress, gen_menus): CSS text, bitmap assets
and the command line.

Each generator writes one luna-*.css; build.sh's luna.css imports them in cascade order,
which matters where rules of equal specificity meet (e.g. the menu check marks must come
after the checkbox rules).
"""
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))   # python -I omits the script dir
import msstyles  # noqa: E402
import ninegrid  # noqa: E402

# GTK 3 has no !important. Base themes use long selectors (e.g. Adwaita's
# check:not(:indeterminate):not(:checked):active:not(:backdrop), which hides the box
# with -gtk-icon-transform: scale(0)). These always-true :not(.class) filters add
# specificity so the Luna rules win whatever the base theme.
BOOST = "".join(f":not(.luna-{i})" for i in range(6))


def scaled(name):
    return f'-gtk-scaled(url("assets/{name}.png"), url("assets/{name}@2.png"), url("assets/{name}@3.png"))'


def save(img, assets, name):
    """`img` as an asset, with pixel-doubled/tripled @2 and @3 copies (GTK must never scale a bitmap)."""
    img.save(assets / f"{name}.png")
    for s in (2, 3):
        img.resize((img.width * s, img.height * s), Image.NEAREST).save(assets / f"{name}@{s}.png")


def stripes(colors, direction):
    """Hard-stop gradient, one stop per pixel (never a repeated bitmap: GTK blurs those)."""
    return ninegrid.fixed_stops(colors, direction)


def rule(sel, **props):
    """A CSS rule; property names use _ for - (a leading _ makes a -gtk-/-Gtk… property)."""
    props = ninegrid.split_layers(props)
    body = "".join(f"  {k.replace('_', '-')}: {v};\n" for k, v in props.items())
    return f"{sel} {{\n{body}}}\n"


def sels(base, pseudos):
    return ", ".join(f"{b}{p}" for b in base for p in pseudos)


def sides(**kw):
    """CSS box shorthand from per-side values (top, right, bottom, left)."""
    return " ".join(kw[k] for k in ("top", "right", "bottom", "left"))


def ms_layers(src, margins, name, assets, tol=0, tile=False, merge=0, solid=False):
    """Nine-grid CSS layers for one part state; corner bitmaps saved as assets."""
    layer_list, corners = ninegrid.layers(src, margins, name, tol, tile, merge, solid)
    for n, img in corners.items():
        save(img, assets, n)
    return ninegrid.css(layer_list, scaled)


def run(title, *generators, post=None):
    """A generator's command line: <assets-dir> <out-css> --msstyles PATH.

    Writes a header comment, then the rules every `generator(th, assets)` returns,
    each passed through `post(rule)` if given."""
    args, th = msstyles.from_argv(sys.argv[1:])
    assets, out_css = (Path(p) for p in args[:2])
    out = []
    for g in generators:
        out += g(th, assets)
    if post:
        out = [post(r) for r in out]
    header = f"/* {title} Generated by tools/{Path(sys.argv[0]).name} from luna.msstyles. */\n"
    out_css.write_text("\n".join([header] + out))
    print(f"wrote {out_css}")
